// Checks src/lib/rv565.ts against the reference test vector from
// github.com/elixpo/rv565 (tests/data/testpattern.rv565). Run: npm run test:rv565
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";

import {
  buildContainer, checkSchedule, decodeFrame, parseContainer, rgb565beToRgba,
  rgbaToRgb565be, testPatternFrame, toCArray, zlibCompress, Rv565Error,
} from "../src/lib/rv565.ts";

const vector = new Uint8Array(readFileSync(new URL("./fixtures/testpattern.rv565", import.meta.url)));

test("parses and decodes the reference vector", async () => {
  const clip = parseContainer(vector);
  assert.deepEqual(clip.header, { width: 180, height: 135, fps: 24, flags: 0, frames: 24 });
  for (let i = 0; i < 24; i++) {
    assert.deepEqual(await decodeFrame(clip, i), testPatternFrame(i, 24, 180, 135), `frame ${i}`);
  }
});

test("encodes a container that decodes to the same frames", async () => {
  const frames = Array.from({ length: 6 }, (_, i) => testPatternFrame(i, 6, 32, 16));
  const payloads = await Promise.all(frames.map(zlibCompress));
  const clip = parseContainer(buildContainer(32, 16, 12, payloads));
  assert.equal(clip.header.frames, 6);
  for (let i = 0; i < 6; i++) assert.deepEqual(await decodeFrame(clip, i), frames[i]);
});

test("rejects malformed files", () => {
  const bad = {
    "not an RV565 file": Uint8Array.of(0x58, ...vector.subarray(1)),
    "unsupported RV565 version": Uint8Array.of(...vector.subarray(0, 3), 5, ...vector.subarray(4)),
    "trailing bytes": Uint8Array.of(...vector, 0),
    "invalid length": vector.subarray(0, vector.length - 1),
    "file too short": vector.subarray(0, 5),
  };
  for (const [message, data] of Object.entries(bad)) {
    assert.throws(() => parseContainer(data), (e) => e instanceof Rv565Error && e.message.includes(message), message);
  }
});

test("pixel conversion round-trips RGB565 values", () => {
  const be = Uint8Array.of(0xf8, 0x00, 0x07, 0xe0, 0x00, 0x1f, 0xff, 0xff, 0x00, 0x00);
  const rgba = rgb565beToRgba(be);
  assert.deepEqual(Array.from(rgba.subarray(0, 4)), [255, 0, 0, 255]);
  assert.deepEqual(Array.from(rgba.subarray(12, 16)), [255, 255, 255, 255]);
  assert.deepEqual(rgbaToRgb565be(rgba), be);
});

test("schedule check matches the paper model", () => {
  const report = checkSchedule(parseContainer(vector), true);
  assert.equal(report.lateFrames, 0);
  assert.equal(report.worstFrameUs, 31312);
});

test("C array matches the format of rv565 c-array", () => {
  const text = toCArray(parseContainer(vector), "testpattern.rv565");
  assert.match(text, /^\/\* Generated by tools\/rv565\.py from testpattern\.rv565: 180x135, 24 FPS, 24 frames\. \*\//);
  assert.match(text, /static const size_t rv565_clip_size = sizeof\(rv565_clip\);\n$/);
});
