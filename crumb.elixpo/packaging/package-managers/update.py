#!/usr/bin/env python3
"""Regenerate the Homebrew formula and WinGet manifests for a release.

Reads the published `.sha256` files of GitHub release `v<VERSION>`, so run it
after the release exists:

    python3 packaging/package-managers/update.py 1.2.0

Writes Formula/crumb.rb and packaging/winget/<VERSION>/. Commit both. The
WinGet manifests are submitted to microsoft/winget-pkgs separately (see
docs/development/release-process.md).
"""

from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

REPO = "elixpo/crumb.elixpo"
ROOT = Path(__file__).resolve().parents[2]
ASSETS = {
    "macos_arm": "crumb-macos-aarch64.tar.gz",
    "macos_intel": "crumb-macos-x86_64.tar.gz",
    "linux_arm": "crumb-linux-aarch64.tar.gz",
    "linux_intel": "crumb-linux-x86_64.tar.gz",
    "windows": "crumb-windows-x86_64.zip",
}
DESCRIPTION = "Self-hosted agent harness and natural-language terminal"
WINGET_ID = "Elixpo.Crumb"
WINGET_SCHEMA = "1.10.0"


def download_url(version: str, asset: str) -> str:
    return f"https://github.com/{REPO}/releases/download/v{version}/{asset}"


def checksum(version: str, asset: str) -> str:
    with urllib.request.urlopen(download_url(version, f"{asset}.sha256"), timeout=30) as response:
        digest = response.read().decode().split()[0]
    if not re.fullmatch(r"[0-9a-f]{64}", digest):
        raise SystemExit(f"{asset}.sha256 does not hold a SHA-256 digest")
    return digest


def formula(version: str, sums: dict[str, str]) -> str:
    def block(key: str) -> str:
        return (
            f'      url "{download_url(version, ASSETS[key])}"\n'
            f'      sha256 "{sums[key]}"'
        )

    return f'''# Generated by packaging/package-managers/update.py; do not edit by hand.
class Crumb < Formula
  desc "{DESCRIPTION}"
  homepage "https://crumb.elixpo.com"
  version "{version}"
  license "MIT"

  on_macos do
    on_arm do
{block("macos_arm")}
    end
    on_intel do
{block("macos_intel")}
    end
  end

  on_linux do
    on_arm do
{block("linux_arm")}
    end
    on_intel do
{block("linux_intel")}
    end
  end

  def install
    bin.install "crumb"
  end

  test do
    assert_match "crumb", shell_output("#{{bin}}/crumb completions bash")
  end
end
'''


def winget(version: str, digest: str) -> dict[str, str]:
    header = (
        f"# Generated by packaging/package-managers/update.py; do not edit by hand.\n"
        f"PackageIdentifier: {WINGET_ID}\nPackageVersion: {version}\n"
    )
    footer = f"ManifestVersion: {WINGET_SCHEMA}\n"

    def schema(kind: str) -> str:
        return (
            f"# yaml-language-server: $schema=https://aka.ms/winget-manifest.{kind}"
            f".{WINGET_SCHEMA}.schema.json\n"
        )

    return {
        f"{WINGET_ID}.yaml": schema("version")
        + header
        + "DefaultLocale: en-US\nManifestType: version\n"
        + footer,
        f"{WINGET_ID}.installer.yaml": schema("installer")
        + header
        + "InstallerType: zip\n"
        + "NestedInstallerType: portable\n"
        + "NestedInstallerFiles:\n"
        + "  - RelativeFilePath: crumb.exe\n"
        + "    PortableCommandAlias: crumb\n"
        + "Installers:\n"
        + "  - Architecture: x64\n"
        + f"    InstallerUrl: {download_url(version, ASSETS['windows'])}\n"
        + f"    InstallerSha256: {digest.upper()}\n"
        + "ManifestType: installer\n"
        + footer,
        f"{WINGET_ID}.locale.en-US.yaml": schema("defaultLocale")
        + header
        + "PackageLocale: en-US\n"
        + "Publisher: Elixpo\n"
        + "PublisherUrl: https://github.com/elixpo\n"
        + f"PublisherSupportUrl: https://github.com/{REPO}/issues\n"
        + "PackageName: Crumb\n"
        + "PackageUrl: https://crumb.elixpo.com\n"
        + "License: MIT\n"
        + f"LicenseUrl: https://github.com/{REPO}/blob/main/LICENSE\n"
        + f"ShortDescription: {DESCRIPTION}\n"
        + "Description: Crumb combines a normal interactive shell with an optional, supervised "
        + "agent runtime, powered by Pollinations by default.\n"
        + "Moniker: crumb\n"
        + "Tags:\n  - agent\n  - ai\n  - cli\n  - terminal\n"
        + f"ReleaseNotesUrl: https://github.com/{REPO}/releases/tag/v{version}\n"
        + "ManifestType: defaultLocale\n"
        + footer,
    }


def main() -> int:
    if len(sys.argv) != 2 or not re.fullmatch(r"\d+\.\d+\.\d+", sys.argv[1]):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    version = sys.argv[1]
    sums = {key: checksum(version, asset) for key, asset in ASSETS.items()}
    formula_path = ROOT / "Formula" / "crumb.rb"
    formula_path.parent.mkdir(exist_ok=True)
    formula_path.write_text(formula(version, sums))
    manifests = ROOT / "packaging" / "winget" / version
    manifests.mkdir(parents=True, exist_ok=True)
    for name, text in winget(version, sums["windows"]).items():
        (manifests / name).write_text(text)
    print(f"wrote {formula_path.relative_to(ROOT)} and {manifests.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
