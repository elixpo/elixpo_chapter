#!/usr/bin/env node
/**
 * Writes src/lib/og-fonts.ts: the subset Inter fonts in assets/og/ as base64,
 * for the fundraiser link-preview card (app/f/[slug]/og.png). Embedding them
 * keeps the card working on the Cloudflare edge runtime with no font fetch.
 *
 * The subsets (Latin, Latin-1, quotes and dashes, "₹", "→") were made with:
 *   python3 -m fontTools.subset Inter-<Weight>.otf \
 *     --unicodes="U+0020-007E,U+00A0-00FF,U+2013-2014,U+2018-201D,U+2022,U+2026,U+20B9,U+2192" \
 *     --layout-features=kern --no-hinting --name-IDs='*' \
 *     --output-file=assets/og/Inter-<Weight>.subset.otf
 *
 * Usage: node scripts/og-fonts.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const fonts = [
    ["INTER_SEMIBOLD", "assets/og/Inter-SemiBold.subset.otf"],
    ["INTER_EXTRABOLD", "assets/og/Inter-ExtraBold.subset.otf"],
];

let out = `// Generated by scripts/og-fonts.mjs from assets/og/*.subset.otf. Do not edit.
// Inter (c) The Inter Project Authors, SIL Open Font License 1.1 (assets/og/OFL.txt).

function bytes(b64: string): ArrayBuffer {
    const bin = atob(b64);
    const buf = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) buf[i] = bin.charCodeAt(i);
    return buf.buffer;
}
`;
for (const [name, path] of fonts) {
    out += `\nexport const ${name}: ArrayBuffer = bytes(\n    "${readFileSync(path).toString("base64")}",\n);\n`;
}
writeFileSync("src/lib/og-fonts.ts", out);
console.log("wrote src/lib/og-fonts.ts");
